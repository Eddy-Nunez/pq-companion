  @doc "Every icon name this module can render, sorted."
  @spec names() :: [String.t()]
  def names, do: @icons |> Map.keys() |> Enum.sort()

  @doc """
  Renders the vendored Lucide icon `name` as an inline `<svg>`.

  Raises `ArgumentError` for an unknown name: a missing icon is a defect in the
  canonical navigation definition (`PQCompanionWeb.Nav`), not something to paper
  over with an empty box.
  """
  attr :name, :string, required: true
  attr :class, :any, default: "size-4"

  def nav_icon(assigns) do
    ~H"""
    {svg(@name, @class)}
    """
  end

  defp svg(name, class) when is_list(class) do
    svg(name, class |> Enum.filter(& &1) |> Enum.join(" "))
  end

  defp svg(name, class) do
    body = @icons[name] || raise ArgumentError, "unknown nav icon: #{inspect(name)}"

    Phoenix.HTML.raw("""
    <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" class="#{class}">#{body}</svg>
    """)
  end
